/// Header of the generated `ui/src/bindings.ts`.
pub const BINDINGS_HEADER: &str = "// Generated by tauri-specta. Do not edit.\n// Regenerate: cargo test -p harvey-app export_bindings";

/// Every app command and event. `run()` uses it for the invoke handler and the events, the tests for the bindings.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    configure(
        tauri_specta::Builder::new()
            .commands(collect_commands![app::app_info])
            .events(collect_events![]),
    )
}

/// Settings shared by the app builder and the test builders: commands resolve to `Result<T, AppError>` (the
/// `api-contract.md` envelope) instead of rejecting.
fn configure(builder: tauri_specta::Builder<tauri::Wry>) -> tauri_specta::Builder<tauri::Wry> {
    builder.error_handling(ErrorHandlingMode::Result)
}

/// Renders the TypeScript bindings of `builder`. The exporter only writes to a path, so this goes through a
/// temporary file (one per call: tests run in parallel).
#[cfg(test)]
fn render_bindings(builder: &tauri_specta::Builder<tauri::Wry>) -> String {
    use std::sync::atomic::{AtomicUsize, Ordering};
    static NEXT: AtomicUsize = AtomicUsize::new(0);

    let path = std::env::temp_dir().join(format!(
        "harvey-app-bindings-{}-{}.ts",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ));
    builder
        .export(
            specta_typescript::Typescript::default().header(BINDINGS_HEADER),
            &path,
        )
        .expect("export bindings");
    let ts = std::fs::read_to_string(&path).expect("read bindings");
    let _ = std::fs::remove_file(&path);
    ts
}

/// The commands `builder` registers, as specta sees them. `Builder` keeps its configuration private; exporting
/// through this language is the public way to read it.
#[cfg(test)]
fn collected(builder: &tauri_specta::Builder<tauri::Wry>) -> Vec<Function> {
    struct Collect<'a>(&'a mut Vec<Function>);

    impl LanguageExt for Collect<'_> {
        type Error = std::io::Error;

        fn export(
            self,
            cfg: &BuilderConfiguration,
            _: &std::path::Path,
        ) -> Result<(), Self::Error> {
            self.0.clone_from(&cfg.commands);
            Ok(())
        }
    }

    let mut functions = Vec::new();
    builder
        .export(Collect(&mut functions), "")
        .expect("collecting never fails");
    functions
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;
    use std::path::Path;

    use super::{COMMANDS, collected, render_bindings, specta_builder};

    #[test]
    fn commands_list_matches_the_builder() {
        let registered: BTreeSet<String> = collected(&specta_builder())
            .iter()
            .map(|f| f.name().to_string())
            .collect();
        let listed: BTreeSet<String> = COMMANDS.iter().map(ToString::to_string).collect();
        assert_eq!(
            registered, listed,
            "COMMANDS (src/commands/names.rs) and collect_commands! differ"
        );
        assert_eq!(listed.len(), COMMANDS.len(), "COMMANDS has a duplicate");
    }

    #[test]
    fn bindings_are_deterministic() {
        assert_eq!(
            render_bindings(&specta_builder()),
            render_bindings(&specta_builder())
        );
    }

    #[test]
    fn bindings_use_the_result_envelope() {
        let ts = render_bindings(&specta_builder());
        assert!(ts.starts_with(super::BINDINGS_HEADER), "{ts}");
        assert!(ts.contains("{ status: \"ok\"; data: T }"), "{ts}");
        assert!(ts.contains("export type AppError"), "{ts}");
    }

    /// Writes `ui/src/bindings.ts`. CI runs it and fails on `git diff --exit-code ui/src/bindings.ts`.
    #[test]
    fn export_bindings() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/bindings.ts");
        std::fs::write(&path, render_bindings(&specta_builder()))
            .expect("write ui/src/bindings.ts");
    }
}
